import type { CivicCase } from '../types/case';

export function generateMarkdownDossier(civicCase: CivicCase): string {
  const lines: string[] = [];

  lines.push(`# [WORK ORDER] ${civicCase.id}: ${civicCase.title}`);
  lines.push(`**Generated via REPAIR.AI Civic Operations Intelligence**`);
  lines.push(``);
  lines.push(`| Field | Specification |`);
  lines.push(`| :--- | :--- |`);
  lines.push(`| **Case ID** | \`${civicCase.id}\` |`);
  lines.push(`| **Status** | **${civicCase.status}** |`);
  lines.push(`| **Category** | ${civicCase.category} |`);
  lines.push(`| **Severity** | **${civicCase.severity.toUpperCase()}** |`);
  lines.push(`| **Priority Score** | ${civicCase.priorityScore} / 100 |`);
  lines.push(`| **Campus Zone** | ${civicCase.zone} |`);
  lines.push(`| **Landmark / Spot** | ${civicCase.landmark} |`);
  lines.push(`| **Assigned Unit** | ${civicCase.assignedTeam || 'Facilities Dispatch'} |`);
  lines.push(`| **Target Response** | ${civicCase.estimatedResponseTarget || 'Standard Tier (24h)'} *(Estimated, non-binding SLA)* |`);
  lines.push(`| **First Reported** | ${new Date(civicCase.createdAt).toLocaleString()} |`);
  lines.push(`| **Last Updated** | ${new Date(civicCase.updatedAt).toLocaleString()} |`);
  lines.push(``);

  lines.push(`## 1. Consolidated Incident Evidence (${civicCase.evidence.length} Corroborating Reports)`);
  civicCase.evidence.forEach((ev, idx) => {
    lines.push(`### Evidence #${idx + 1} — ${ev.reporterLabel} (\`${ev.reportId}\`)`);
    lines.push(`- **Logged At:** ${new Date(ev.timestamp).toLocaleString()}`);
    lines.push(`- **Location Note:** ${ev.landmark || civicCase.landmark}`);
    lines.push(`- **Observation:** ${ev.description}`);
    lines.push(``);
  });

  if (civicCase.aiAnalysis) {
    const ai = civicCase.aiAnalysis;
    lines.push(`## 2. Multimodal AI Analysis (Model: \`${ai.modelUsed}\`${ai.isSimulated ? ' [Simulated Demo]' : ' [Live API]'})`);
    lines.push(`- **Confidence Score:** ${(ai.confidenceScore * 100).toFixed(1)}%`);
    lines.push(`- **Accessibility Impact:** ${ai.accessibilityImpact}`);
    lines.push(`- **Urgency Rationale:** ${ai.urgencyRationale}`);
    lines.push(`- **Recommended Action:** ${ai.recommendedAction}`);
    lines.push(``);
    lines.push(`### Detected Hazards`);
    ai.detectedHazards.forEach(h => lines.push(`- [x] ${h}`));
    lines.push(``);
    if (ai.uncertaintyFlags && ai.uncertaintyFlags.length > 0) {
      lines.push(`### Epistemic Uncertainty & Inspection Limits`);
      ai.uncertaintyFlags.forEach(u => lines.push(`- [ ] *Requires On-Site Physical Check:* ${u}`));
      lines.push(``);
    }
  }

  if (civicCase.clarificationAnswers.length > 0) {
    lines.push(`## 3. Human Clarification Log`);
    civicCase.clarificationAnswers.forEach(ans => {
      lines.push(`- **Q:** *${ans.question}*`);
      lines.push(`  **A:** ${ans.answer} *(Answered by ${ans.answeredBy} at ${new Date(ans.answeredAt).toLocaleTimeString()})*`);
    });
    lines.push(``);
  }

  if (civicCase.mergeHistory.length > 0) {
    lines.push(`## 4. Duplicate Evidence Clustering History`);
    civicCase.mergeHistory.forEach((m, idx) => {
      lines.push(
        `${idx + 1}. **Report \`${m.mergedReportId}\`** by *${m.reporterLabel}* merged at ${new Date(m.mergedAt).toLocaleTimeString()} with ${m.duplicateScore}% match confidence.`
      );
      lines.push(`   *Breakdown:* Zone: ${m.scoreBreakdown.zoneScore}pts, Category: ${m.scoreBreakdown.categoryScore}pts, Keywords: ${m.scoreBreakdown.keywordScore}pts`);
    });
    lines.push(``);
  }

  if (civicCase.verification) {
    const v = civicCase.verification;
    lines.push(`## 5. Visual Repair Verification`);
    lines.push(`- **Status:** **${v.verificationStatus}**`);
    lines.push(`- **Confidence Score:** ${(v.confidenceScore * 100).toFixed(1)}%`);
    lines.push(`- **Observed Visual Changes:**`);
    v.visualChangesObserved.forEach(c => lines.push(`  - ${c}`));
    if (v.remainingConcerns.length > 0) {
      lines.push(`- **Remaining Notes / Caution:**`);
      v.remainingConcerns.forEach(rc => lines.push(`  - ⚠️ ${rc}`));
    }
    lines.push(``);
    lines.push(`> **COMPLIANCE DISCLAIMER:** ${v.complianceDisclaimer}`);
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`*Generated by REPAIR.AI — Open Source Civic Infrastructure Intelligence*`);

  return lines.join('\n');
}

export async function copyDossierToClipboard(civicCase: CivicCase): Promise<boolean> {
  try {
    const markdown = generateMarkdownDossier(civicCase);
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(markdown);
      return true;
    } else {
      // Fallback
      const textarea = document.createElement('textarea');
      textarea.value = markdown;
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
      return true;
    }
  } catch (err) {
    console.error('Failed to copy dossier to clipboard:', err);
    return false;
  }
}

